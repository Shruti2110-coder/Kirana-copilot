/** "today" / "yesterday" / "3 days ago" in the chosen language. */
export function agoIn(locale: Locale, iso: string | null) {
  if (!iso) return "";
  const t = dict(locale);
  const d = Math.floor((Date.now() - new Date(iso).getTime()) / 86_400_000);
  if (d <= 0) return t.today;
  if (d === 1) return t.yesterday;
  return t.daysAgo(d);
}
